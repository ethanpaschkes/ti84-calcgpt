#!/usr/bin/env python3
"""Writes src/typing_tables.h from reels/mac/calckeys.py, so the calculator-side typing layout and the Mac-side one
(used by --control) come from one table and can never disagree. Run after changing the layout in calckeys.py."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, "..", "..", "reels", "mac"))
import calckeys as K

def table(chars):
    arr = [0] * 64
    for (g, bit), name in K.KEYS.items():
        ch = chars.get(name)
        if ch:
            assert len(ch) == 1 and ord(ch) < 128
            arr[g * 8 + bit] = ord(ch)
    return arr

def emit(name, arr, comment):
    rows = [", ".join(f"{v:3d}" for v in arr[i:i + 8]) for i in range(0, 64, 8)]
    return f"/* {comment} */\nstatic const unsigned char {name}[64] = {{\n    " + ",\n    ".join(rows) + "\n};\n"

text = ("/* Generated by tools/gen_typing_tables.py from reels/mac/calckeys.py. Do not edit by hand.\n"
        " * A key is numbered group * 8 + bit, where group is the calculator's keyboard group 1 to 7 and bit is 0 to 7;\n"
        " * 0 means the key types nothing in that layer. */\n#ifndef TYPING_TABLES_H\n#define TYPING_TABLES_H\n\n"
        + emit("TY_LETTERS", table(K.LETTERS), "typed with the Alpha layer on (lower case)")
        + "\n" + emit("TY_NORMAL", table(K.NORMAL), "typed normally: digits and symbols")
        + "\n" + emit("TY_SHIFTED", table(K.SHIFTED), "typed after the 2nd key")
        + "\n#endif\n")
for target in ("..", "../../calcgpt", "../../calcos", "../../gptdemo"):   # every calculator program that types gets the same table
    folder = os.path.join(here, target, "src")
    if os.path.isdir(folder):
        open(os.path.join(folder, "typing_tables.h"), "w").write(text)
        print("wrote", os.path.normpath(os.path.join(folder, "typing_tables.h")))
